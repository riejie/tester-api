import { Pool, type PoolClient } from 'pg'

const testTable = 'public.social_platform_connection_smoke_test'

export class ConfigurationError extends Error {}

let databasePool: Pool | undefined

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null
}

function providerErrorText(value: unknown): string | undefined {
  if (typeof value !== 'string') {
    return undefined
  }

  const text = value.replace(/[\r\n\t]+/g, ' ').trim().slice(0, 160)
  return text || undefined
}

function getDatabasePool(): Pool {
  const connectionString = process.env.SUPABASE_DB_URL
  if (!connectionString) {
    throw new ConfigurationError('SUPABASE_DB_URL is not configured on Railway')
  }

  databasePool ??= new Pool({
    connectionString,
    max: 2,
    connectionTimeoutMillis: 5000,
    idleTimeoutMillis: 10000,
  })

  return databasePool
}

async function withDatabaseClient<T>(
  operation: (client: PoolClient) => Promise<T>,
): Promise<T> {
  const client = await getDatabasePool().connect()
  try {
    return await operation(client)
  } finally {
    client.release()
  }
}

