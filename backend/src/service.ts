export async function sendTestEmail(to: string): Promise<void> {
  const apiKey = process.env.BREVO_API_KEY
  const senderEmail = process.env.BREVO_SENDER_EMAIL
  if (!apiKey || !senderEmail) {
    throw new ConfigurationError('BREVO_API_KEY and BREVO_SENDER_EMAIL must be configured on Railway')
  }

  const response = await fetch('https://api.brevo.com/v3/smtp/email', {
    method: 'POST',
    headers: {
      accept: 'application/json',
      'api-key': apiKey,
      'content-type': 'application/json',
    },
    body: JSON.stringify({
      sender: { email: senderEmail },
      to: [{ email: to }],
      subject: 'Social Platform connection test',
      textContent: 'This is a test email sent by the Social Platform connection tester.',
    }),
  })

  if (!response.ok) {
    let providerDetails: string[] = []
    try {
      const payload: unknown = await response.json()
      if (isRecord(payload)) {
        const message = providerErrorText(payload.message)
        const code = providerErrorText(payload.code)
        providerDetails = [
          ...(message ? [message] : []),
          ...(code ? [`code: ${code}`] : []),
        ]
      }
    } catch (error) {
      if (!(error instanceof SyntaxError)) {
        throw error
      }
    }

    const detail = providerDetails.length > 0 ? `: ${providerDetails.join(' — ')}` : ''
    throw new Error(
      `Brevo rejected the test email (HTTP ${response.status})${detail}. Check that Railway has a valid API v3 key for the correct Brevo account.`,
    )
  }
}

