export async function createTestTable(): Promise<{ created: boolean }> {
  return withDatabaseClient(async (client) => {
    const existing = await client.query<{ exists: boolean }>(
      'SELECT to_regclass($1) IS NOT NULL AS exists',
      [testTable],
    )

    await client.query(`
      CREATE TABLE IF NOT EXISTS ${testTable} (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `)

    return { created: !existing.rows[0]?.exists }
  })
}

export async function deleteTestTable(): Promise<{ deleted: boolean }> {
  return withDatabaseClient(async (client) => {
    const existing = await client.query<{ exists: boolean }>(
      'SELECT to_regclass($1) IS NOT NULL AS exists',
      [testTable],
    )

    await client.query(`DROP TABLE IF EXISTS ${testTable}`)
    return { deleted: Boolean(existing.rows[0]?.exists) }
  })
}